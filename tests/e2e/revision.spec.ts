import { test, expect } from '@playwright/test'

const digestionChapter = 'Digestion et absorption intestinale'

test('définitions SQLite : trois colonnes, chapitres, recherche et provenance', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/definitions')
  await expect(page.getByRole('heading', { name: 'Mes définitions' })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'Titre du chapitre' })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'Nom / concept' })).toBeVisible()
  await expect(page.getByRole('columnheader', { name: 'Définition', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: '120 notions' })).toBeVisible()
  await expect(page.locator('.definition-table tbody tr')).toHaveCount(20)
  await page.getByRole('button', { name: 'Suivant', exact: true }).click()
  await expect(page.getByText('Page 2 / 6')).toBeVisible()
  await page.getByLabel('Titre du chapitre', { exact: true }).selectOption(digestionChapter)
  await expect(page.locator('.definition-table tbody tr')).toHaveCount(7)
  await page.getByLabel('Rechercher une notion').fill('villosites')
  await expect(page.locator('.definition-table tbody tr')).toHaveCount(1)
  await expect(page.locator('.definition-table tbody')).toContainText('Villosités intestinales')
  await expect(page.locator('.definition-table tbody')).toContainText('p. 8')
  await page.reload()
  await expect(page.locator('.definition-table tbody tr')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `artifacts/definitions-${testInfo.project.name}.png`, fullPage: true })
  await page.getByLabel('Rechercher une notion').fill('inexistant-123')
  await expect(page.getByRole('heading', { name: 'Aucune définition dans cette sélection' })).toBeVisible()
  await page.getByRole('button', { name: 'Réinitialiser les filtres' }).click()
  await page.getByLabel('Rechercher une notion').fill('Glucagon')
  await expect(page.locator('.definition-review-note')).toContainText('Incohérence dans le PDF')
  await expect(page.locator('.definition-table tbody')).toContainText('hormone hypoglycémiante')
  await expect(page.locator('.definition-table tbody')).toContainText('p. 39')
  expect(errors).toEqual([])
})

test('navigation, flashcards du PDF, clavier et progression persistante', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'CRPE – Espace de révision' })).toBeVisible()
  await expect(page.locator('.domain-card').filter({ hasText: 'Sciences' })).toContainText('120 cartes')
  await expect(page.locator('.demo-notice')).toHaveCount(0)
  await page.locator('.domain-card').filter({ hasText: 'Sciences' }).click()
  await page.getByLabel('Catégorie', { exact: true }).selectOption(digestionChapter)
  await expect(page.locator('.card-list-row')).toHaveCount(7)
  await expect(page.getByRole('link', { name: 'Lancer le quiz 7', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Réviser 7 cartes' }).click()
  await expect(page.locator('.card-question')).toHaveText('Digestion')
  const flipCard = page.locator('.flashcard')
  await page.keyboard.press('Space')
  await expect(flipCard).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.card-explanation')).toHaveCount(0)
  await expect(page.locator('.card-answer')).toContainText('transformations mécaniques et chimiques')
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('.session-progress')).toContainText('2 / 7')
  await page.keyboard.press('ArrowLeft')
  await expect(page.locator('.session-progress')).toContainText('1 / 7')
  await page.getByRole('button', { name: 'Je connais', exact: true }).click()
  await page.getByRole('button', { name: 'À revoir', exact: true }).click()
  await page.reload()
  const progress = await page.evaluate(() => JSON.parse(localStorage.getItem('crpe-progress-v1')!))
  expect(Object.values(progress.cards).filter((entry: unknown) => (entry as { status: string }).status === 'known')).toHaveLength(1)
  expect(Object.values(progress.cards).filter((entry: unknown) => (entry as { status: string }).status === 'review')).toHaveLength(1)
  await page.goto('/domaine/sciences?statut=review')
  await page.getByRole('link', { name: 'Réviser 1 carte', exact: true }).click()
  await page.getByRole('button', { name: 'Je connais', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Série terminée !' })).toBeVisible()
  await page.goto('/domaine/sciences/quiz?categorie=inconnue')
  await expect(page.getByRole('heading', { name: 'Pas de quiz pour cette sélection.' })).toBeVisible()
  expect(errors).toEqual([])
})

test('thème persistant, routes directes et navigation mobile', async ({ page }, testInfo) => {
  await page.goto('/domaine/references')
  await expect(page.getByRole('heading', { name: 'Références', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Références', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Activer le mode sombre' }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: 'Activer le mode clair' }).click()
  await page.goto('/')
  if (testInfo.project.name === 'mobile') {
    await page.getByRole('button', { name: 'Ouvrir le menu' }).click()
    await page.getByRole('link', { name: 'Mes définitions', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Mes définitions' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Ouvrir le menu' })).toHaveAttribute('aria-expanded', 'false')
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.goto('/page-inconnue')
  await expect(page.getByRole('heading', { name: 'Cette page est introuvable.' })).toBeVisible()
})

test('préférence de mouvement réduit et erreur de chargement de base', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/domaine/sciences/flashcards')
  await page.getByRole('button', { name: 'Retourner', exact: true }).click()
  await expect(page.locator('.card-back')).toBeVisible()
  await expect(page.locator('.card-front')).toBeHidden()
  await page.route('**/*.sqlite*', route => route.request().resourceType() === 'fetch' ? route.abort() : route.continue())
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Les définitions n’ont pas pu être chargées.' })).toBeVisible()
  await page.unroute('**/*.sqlite*')
  await page.getByRole('button', { name: 'Réessayer' }).click()
  await expect(page.getByRole('heading', { name: 'Une carte, un déclic.' })).toBeVisible()
})
