import { test, expect } from '@playwright/test'

test('références : titre, auteur, deux passages, filtres et source', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/domaine/references')
  await page.getByRole('link', { name: 'Consulter les références littéraires' }).click()
  await expect(page.getByRole('heading', { name: 'Mes références littéraires' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '16 références' })).toBeVisible()
  await expect(page.locator('.reference-entry')).toHaveCount(8)
  await page.getByRole('button', { name: 'Suivant', exact: true }).click()
  await expect(page.getByText('Page 2 / 2', { exact: true })).toBeVisible()
  await page.getByLabel('Rechercher une référence').fill('petit prince')
  const entry = page.locator('.reference-entry')
  await expect(entry).toHaveCount(1)
  await expect(entry.getByRole('heading', { name: 'Le Petit Prince', exact: true })).toBeVisible()
  await expect(entry.locator('.reference-creator')).toContainText('Antoine de Saint-Exupéry')
  await expect(entry.locator('.reference-presentation')).toContainText('On peut également penser au Petit Prince')
  await expect(entry.locator('.reference-analysis')).toContainText('Cette référence montre que la découverte de l’autre')
  await expect(entry.locator('footer')).toContainText('Feuil1, ligne 2')
  await page.reload()
  await expect(entry).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `artifacts/references-${testInfo.project.name}.png`, fullPage: true })
  await page.getByLabel('Rechercher une référence').fill('')
  await page.getByLabel('Thème', { exact: true }).selectOption('ouverture aux autres')
  await expect(entry).toHaveCount(1)
  await page.getByLabel('Thème', { exact: true }).selectOption('')
  await page.getByLabel('Auteur / réalisateur', { exact: true }).selectOption('Émile Zola')
  await expect(entry.getByRole('heading', { name: 'Germinal', exact: true })).toBeVisible()
  await page.getByLabel('Auteur / réalisateur', { exact: true }).selectOption('')
  await page.getByLabel('État du contenu').selectOption('incomplete')
  await expect(page.getByRole('heading', { name: '3 références', exact: true })).toBeVisible()
  await expect(entry).toHaveCount(3)
  await expect(page.locator('.reference-missing')).toHaveCount(4)
  await page.getByLabel('Rechercher une référence').fill('inexistant-123')
  await expect(page.getByRole('heading', { name: 'Aucune référence dans cette sélection' })).toBeVisible()
  expect(errors).toEqual([])
})

test('flashcards littéraires : titre et auteur, passages, sélection et sauvegarde', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/references?recherche=Candide')
  await page.getByRole('link', { name: 'Réviser cette référence', exact: true }).click()
  await expect(page.locator('.session-progress')).toContainText('1 / 1')
  await expect(page.locator('.card-question')).toContainText('Candide')
  await expect(page.locator('.flashcard-reference-creator')).toHaveText('Voltaire')
  await page.getByRole('button', { name: 'Retourner', exact: true }).click()
  await expect(page.locator('.card-back .reference-presentation')).toContainText('On peut également penser à Candide')
  await expect(page.locator('.card-back .reference-analysis')).toContainText('Cette référence montre que')
  await page.getByRole('button', { name: 'Je connais', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Série terminée !' })).toBeVisible()
  await page.goto('/domaine/references?statut=known')
  await expect(page.locator('.card-list-row')).toHaveCount(1)
  await expect(page.locator('.card-list-row')).toContainText('Candide')
  await page.reload()
  await expect(page.locator('.card-list-row')).toHaveCount(1)
})
